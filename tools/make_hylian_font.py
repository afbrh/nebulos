for k,v in G.items():
    if len(v) == 6: G[k] = v + ["     "]  # C is drawn 6 rows high: pad
    assert len(G[k]) == 7 and all(len(r) == 5 for r in G[k]), k

U = 100          # font units per pixel
BX, BY = 50, 30  # emboldening: each pixel is drawn this much wider/taller (overlaps its neighbours)
ADV = 7 * U + BX  # 5px glyph + 2px gap
ASC = 7 * U
names = [".notdef"] + ["space" if c == " " else f"u{ord(c):04X}" for c in G]
cmap = {ord(c): ("space" if c == " " else f"u{ord(c):04X}") for c in G}
for c in "abcdefghijklmnopqrstuvwxyz": cmap[ord(c)] = f"u{ord(c.upper()):04X}"

def glyph(rows):
    pen = TTGlyphPen(None)
    for y, row in enumerate(rows):
        for x, ch in enumerate(row):
            if ch == "#":
                X0, Y1 = x * U, ASC - y * U
                pen.moveTo((X0, Y1 - U)); pen.lineTo((X0, Y1 + BY)); pen.lineTo((X0 + U + BX, Y1 + BY)); pen.lineTo((X0 + U + BX, Y1 - U)); pen.closePath()
    return pen.glyph()

glyphs = {".notdef": glyph(["#####"] + ["#   #"] * 5 + ["#####"])}
for c, rows in G.items(): glyphs["space" if c == " " else f"u{ord(c):04X}"] = glyph(rows)
fb = FontBuilder(1000, isTTF=True)
fb.setupGlyphOrder(names); fb.setupCharacterMap(cmap); fb.setupGlyf(glyphs)
fb.setupHorizontalMetrics({n: (ADV, 0) for n in names})
fb.setupHorizontalHeader(ascent=ASC + U, descent=-2 * U)
fb.setupNameTable({"familyName": "Hylian Pixel", "styleName": "Regular"})
fb.setupOS2(sTypoAscender=ASC + U, sTypoDescender=-2 * U, usWinAscent=ASC + U, usWinDescent=2 * U)
fb.setupPost(); fb.save(sys.argv[1])
